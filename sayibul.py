def parse_arsiv(raw: str):
    rows = []
    for line in raw.strip().split('\n'):
        parts = line.split('\t')
        if len(parts) < 3:
            continue
        try:
            hafta = int(parts[0])
            tarih = parts[1]
            sayilar = []
            for x in parts[2:]:
                try:
                    n = int(x)
                    if 1 <= n <= 80 and n not in sayilar:
                        sayilar.append(n)
                except:
                    pass
            if sayilar:
                rows.append({"hafta": hafta, "tarih": tarih, "tarih_str": tarih, "sayilar": sayilar})
        except:
            pass
    rows.sort(key=lambda r: r["hafta"], reverse=True)
    return rows

